#!/usr/bin/env python3
"""
Android strings → iOS Localizable.strings (the Android → iOS sync rule, docs/modules/ios/README.md).

Reads every androidApp/app/src/main/res/values{,-ar}/*.xml and writes
iosApp/Dorr/Resources/{en,ar}.lproj/Localizable.strings with the same keys, so
`L("login_title")` on iOS is `stringResource(R.string.login_title)` on Android.

Never edit the generated files by hand: change the Android XML and run
    python3 iosApp/scripts/sync_strings.py
(the Claude Code hook in .claude/settings.json runs it after every edit of those files).

Formats: %1$s → %1$@, %s → %@, %1$d → %1$ld, %d → %ld (Swift Int is 64-bit).
<plurals> become `key##one` / `key##other` entries (read with `Lp("key", n)`).
<string-array> items become `key##0`, `key##1`… (read with `La("key")`).
translatable="false" duplicates are skipped.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "androidApp" / "app" / "src" / "main" / "res"
OUT = ROOT / "iosApp" / "Dorr" / "Resources"

# Android folder → iOS language folder.
LANGS = {"values": "en", "values-ar": "ar"}

FORMAT = re.compile(r"%(\d+\$)?([-#+ 0,(]*\d*(?:\.\d+)?)([sdfxXc])")


def text_of(el: ET.Element) -> str:
    # Inline markup (<b>, <u>, <xliff:g>) keeps only its text, as on Android without Html.fromHtml.
    raw = "".join(el.itertext())
    if len(raw) >= 2 and raw[0] == raw[-1] == '"':
        raw = raw[1:-1]
    out, i = [], 0
    while i < len(raw):
        ch = raw[i]
        if ch == "\\" and i + 1 < len(raw):
            nxt = raw[i + 1]
            out.append({"n": "\n", "t": "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?"}.get(nxt, nxt))
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def to_ios_format(value: str) -> str:
    def swap(m: re.Match) -> str:
        pos, flags, kind = m.group(1) or "", m.group(2), m.group(3)
        if kind == "s":
            return f"%{pos}{flags}@"
        if kind == "d":
            return f"%{pos}{flags}ld"
        return m.group(0)

    return FORMAT.sub(swap, value)


def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def read_folder(folder: pathlib.Path) -> dict:
    entries = {}
    for xml in sorted(folder.glob("*.xml")):
        try:
            root = ET.parse(xml).getroot()
        except ET.ParseError as e:
            print(f"skip {xml.relative_to(ROOT)}: {e}", file=sys.stderr)
            continue
        for el in root:
            name = el.get("name")
            if not name:
                continue
            if el.tag == "string":
                entries[name] = to_ios_format(text_of(el))
            elif el.tag == "string-array":
                for i, item in enumerate(el.findall("item")):
                    entries[f"{name}##{i}"] = to_ios_format(text_of(item))
            elif el.tag == "plurals":
                for item in el.findall("item"):
                    entries[f"{name}##{item.get('quantity')}"] = to_ios_format(text_of(item))
    return entries


def main() -> int:
    english = read_folder(RES / "values")
    for android, ios in LANGS.items():
        entries = read_folder(RES / android)
        if ios != "en":
            # A key missing in Arabic falls back to English, as Android does.
            entries = {**english, **entries}
        target = OUT / f"{ios}.lproj" / "Localizable.strings"
        target.parent.mkdir(parents=True, exist_ok=True)
        lines = [
            "/* Generated by iosApp/scripts/sync_strings.py from androidApp res/"
            f"{android}/*.xml — do not edit. */",
            "",
        ]
        lines += [f'"{escape(k)}" = "{escape(v)}";' for k, v in sorted(entries.items())]
        target.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{target.relative_to(ROOT)}: {len(entries)} strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
